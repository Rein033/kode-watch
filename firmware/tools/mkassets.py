#!/usr/bin/env python3
"""Make main/kos_assets.c: kodeOS's fonts and glyphs for the watch, as 4-bit alpha maps.

Fonts come from the kode SDK's TTFs (Outfit, DM Sans; SIL OFL), at the sizes
kodeOS uses for its roles. Glyphs come from kodeOS's own A8 images (GPL-3.0).

    mkassets.py <KodeOS checkout> <out.c> <out.h>
"""
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

KOS = Path(sys.argv[1])
OUT_C, OUT_H = Path(sys.argv[2]), Path(sys.argv[3])
TTF = KOS / "sdk/components/kui/fonts/assets"

ASCII = "".join(chr(c) for c in range(32, 127))
FONTS = [  # name, ttf, px, chars
    ("caption", "Outfit-Regular.ttf", 22, ASCII),
    ("body", "Outfit-Regular.ttf", 28, ASCII),
    ("name", "Outfit-Bold.ttf", 28, ASCII),
    ("title", "Outfit-Bold.ttf", 34, ASCII),
    ("figure", "DMSans-Bold.ttf", 40, "0123456789:%.-+ s"),
    ("clock", "DMSans-Bold.ttf", 104, "0123456789:- "),
]
GLYPHS = ["wifi_46", "bt_46", "more_46", "power_46", "share_46", "sun3_52", "sun1_52",
          "clock_40", "home_40", "list_40", "note_40", "gauge_40", "heart_40", "pin_40"]


def pack4(alpha_bytes):
    """8-bit alpha to 4-bit, two pixels a byte, high nibble first; rows not padded."""
    out = bytearray()
    a = [v >> 4 for v in alpha_bytes]
    if len(a) % 2:
        a.append(0)
    for i in range(0, len(a), 2):
        out.append((a[i] << 4) | a[i + 1])
    return out


def c_bytes(b):
    return ",".join(f"0x{v:02x}" for v in b)


def font(name, ttf, px, chars):
    f = ImageFont.truetype(str(TTF / ttf), px)
    asc, desc = f.getmetrics()
    cap = -f.getbbox("H", anchor="ls")[1]
    glyphs, bits = [], bytearray()
    for ch in chars:
        x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        adv = int(round(f.getlength(ch)))
        off = len(bits)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
            bits += pack4(im.tobytes())
        glyphs.append((ord(ch), off, w, h, x0, y0, adv))
    return dict(name=name, asc=asc, desc=desc, cap=cap, lh=asc + desc, glyphs=glyphs, bits=bits)


def glyph_image(stem):
    src = (KOS / f"components/kgui/glyphs/kgui_glyph_{stem}.c").read_text()
    w = int(re.search(r"\.w\s*=\s*(\d+)", src).group(1))
    h = int(re.search(r"\.h\s*=\s*(\d+)", src).group(1))
    assert "LV_COLOR_FORMAT_A8" in src, stem
    body = src[src.index("{", src.index("[]")) + 1:]
    body = body[:body.index("};")]
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body))
    stride = len(data) // h
    rows = b"".join(data[r * stride:r * stride + w] for r in range(h))
    return dict(name=stem, w=w, h=h, bits=pack4(rows))


fonts = [font(*f) for f in FONTS]
icons = [glyph_image(g) for g in GLYPHS]

c = ["/* Generated by tools/mkassets.py from the kode SDK's fonts (SIL OFL) and kodeOS's glyphs (GPL-3.0). */",
     '#include "kos_assets.h"', ""]
for fo in fonts:
    n = fo["name"]
    c.append(f"static const uint8_t {n}_bits[] = {{{c_bytes(fo['bits'])}}};")
    c.append(f"static const kf_glyph_t {n}_glyphs[] = {{")
    for (cp, off, w, h, x0, y0, adv) in fo["glyphs"]:
        c.append(f"    {{{cp}, {off}, {w}, {h}, {x0}, {y0}, {adv}}},")
    c.append("};")
    c.append(f"const kf_font_t KF_{n.upper()} = {{{n}_glyphs, {n}_bits, {len(fo['glyphs'])}, "
             f"{fo['asc']}, {fo['desc']}, {fo['cap']}, {fo['lh']}}};")
    c.append("")
for ic in icons:
    c.append(f"static const uint8_t ic_{ic['name']}_bits[] = {{{c_bytes(ic['bits'])}}};")
    c.append(f"const kf_icon_t KI_{ic['name'].upper()} = {{{ic['w']}, {ic['h']}, ic_{ic['name']}_bits}};")
OUT_C.write_text("\n".join(c) + "\n")

h = ["/* Generated by tools/mkassets.py. */", "#ifndef KOS_ASSETS_H_", "#define KOS_ASSETS_H_", "",
     "#include <stdint.h>", "",
     "typedef struct { uint16_t cp; uint32_t off; uint8_t w, h; int8_t x0, y0; uint8_t adv; } kf_glyph_t;",
     "/** A 4-bit alpha font; y0 is the glyph's top from the baseline (negative is up). */",
     "typedef struct { const kf_glyph_t *g; const uint8_t *bits; uint16_t n; uint8_t asc, desc, cap, lh; } kf_font_t;",
     "typedef struct { uint8_t w, h; const uint8_t *bits; } kf_icon_t;", ""]
for fo in fonts:
    h.append(f"extern const kf_font_t KF_{fo['name'].upper()};")
for ic in icons:
    h.append(f"extern const kf_icon_t KI_{ic['name'].upper()};")
h += ["", "#endif", ""]
OUT_H.write_text("\n".join(h))
total = sum(len(f["bits"]) for f in fonts) + sum(len(i["bits"]) for i in icons)
print(f"fonts {len(fonts)}, icons {len(icons)}, {total} bytes of bitmaps")
